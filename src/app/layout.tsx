import type { Metadata } from "next";
import localFont from "next/font/local";
import "@/_styles/global/globals.css";

// Brand typeface: Diodrum. Self-hosted WOFF2 with font-display: swap and a metric-adjusted Arial
// fallback, so text shows immediately and doesn't shift when the font arrives.
// The family has Regular and Medium only: Medium serves every heavier weight (500–900), so bold
// text uses the real Medium face instead of a blurry browser-synthesized bold.
const brandFont = localFont({
  src: [
    { path: "../_assets/fonts/Diodrum-Regular.woff2", weight: "100 499", style: "normal" },
    { path: "../_assets/fonts/Diodrum-Medium.woff2", weight: "500 900", style: "normal" },
  ],
  variable: "--font-brand",
  display: "swap",
  fallback: ["Arial", "Helvetica", "sans-serif"],
  adjustFontFallback: "Arial",
});

export const metadata: Metadata = {
  title: "User Panel",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    // data-scroll-behavior: smooth scroll for in-page anchors (header nav), while Next keeps route changes instant
    <html lang="pt-BR" data-scroll-behavior="smooth" className={`${brandFont.variable} h-full antialiased`}>
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
